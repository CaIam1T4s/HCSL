using System.Security.Cryptography;
using System.Text;
namespace HCSL.Core;

/// <summary>A deterministic, launcher-owned CS2 map group generated into one deployment.</summary>
public sealed record ServerMapGroupPlan(string Name, string StartupMap, string Content, string Hash);

public static class ServerMapGroupRules
{
    public const string FileName = "gamemodes_server.txt";
    public const string ManagedMarker = "// Generated by HCSL from the preset map pool. Do not edit; redeploy to regenerate.";

    /// <summary>The group is tied to the preset, so it is stable across redeployments of that preset.</summary>
    public static string GroupName(Guid presetId)
    {
        if (presetId == Guid.Empty) throw new InstanceException("HCSL-MAPGROUP-ID", "A stable preset ID is required.");
        // Keep the name below the engine's short KeyValues key budget. Base CS2 groups are at most
        // 31 characters; a full 32-digit GUID produced 37 and was accepted by +mapgroup but did not
        // resolve to its definition on a real server.
        return "hcsl_" + presetId.ToString("N")[..16];
    }

    /// <summary>
    /// Native map groups only cover built-in maps here. Workshop and mixed pools keep the existing
    /// manual/live-change behavior; they must not be presented as an engine rotation.
    /// The configured startup map must belong to the group, otherwise CS2 would start outside it.
    /// </summary>
    public static ServerMapGroupPlan? Create(Guid presetId, string startupMap, PresetMapPool pool)
    {
        MapPoolRules.Validate(pool);
        if (pool.Maps.Length == 0 || pool.Maps.Any(m => m.Kind != ServerMapKind.Standard)) return null;
        if (!pool.Maps.Any(m => string.Equals(m.Value, startupMap, StringComparison.OrdinalIgnoreCase)))
            throw new InstanceException("HCSL-MAPGROUP-STARTUP", "The preset startup map must be one of the standard maps in its map pool.");
        var name = GroupName(presetId);
        var content = Build(name, pool.Maps);
        return new(name, startupMap, content, Hash(content));
    }

    public static string Hash(string content) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(content)));

    private static string Build(string name, ServerMapTarget[] maps)
    {
        var text = new StringBuilder();
        text.Append(ManagedMarker).Append('\n');
        text.Append("\"GameModes_Server.txt\"\n{\n");
        // The group must be registered for the active game mode as well as defined below;
        // otherwise CS2 sets the group name but reports an empty map list.
        text.Append("\t\"gameTypes\"\n\t{\n");
        text.Append("\t\t\"classic\"\n\t\t{\n");
        text.Append("\t\t\t\"gameModes\"\n\t\t\t{\n");
        text.Append("\t\t\t\t\"competitive\"\n\t\t\t\t{\n");
        text.Append("\t\t\t\t\t\"mapgroupsMP\"\n\t\t\t\t\t{\n");
        text.Append("\t\t\t\t\t\t\"").Append(name).Append("\"\t\t\"\"\n");
        text.Append("\t\t\t\t\t}\n\t\t\t\t}\n\t\t\t}\n\t\t}\n\t}\n");
        text.Append("\t\"mapgroups\"\n\t{\n");
        text.Append("\t\t\"").Append(name).Append("\"\n\t\t{\n");
        text.Append("\t\t\t\"name\"\t\t\"").Append(name).Append("\"\n");
        text.Append("\t\t\t\"maps\"\n\t\t\t{\n");
        foreach (var map in maps)
            text.Append("\t\t\t\t\"").Append(map.Value).Append("\"\t\t\"\"\n");
        text.Append("\t\t\t}\n\t\t}\n\t}\n}\n");
        return text.ToString();
    }
}
